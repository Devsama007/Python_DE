"""Python Escape Sequence"""

"""
"" = Double Quote
'' = Single Quote
\" = Double Quote
\' = Single Quote
\\ = Backslash
\n = New Line
\t = Tab
\b = Backspace
"""

# Double Quote & Single Quote
'''Used to print script'''
print("Hello World")


# Double Quote & Single Quote with slash
''' Used to add double quote and single quote in the script'''
print("Hi \"Python\"")


#Escape Backslash
''' Used to add backslash in the script'''
print("Path: C:\\Users\\Baraa")


# New Line
''' Used to add new line in the script'''  
print("Hi there \nWelcome to Python")


# Tab
''' Used to add tab in the script, means spaces in line'''
print("Hi there \tWhats up")


# Backspace
''' Used to add backspace in the script, means remove the last character'''
'''it does not delete characters; it simply moves the terminal cursor one position to the left'''
print("Hi there \bWhats up")
